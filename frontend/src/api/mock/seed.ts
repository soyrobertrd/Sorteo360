/**
 * El historial de envíos que en modo http sirve notification-service: cinco envíos, seis
 * destinatarios. Cada `about` apunta a un evento sembrado arriba, así que la línea OPT • evento
 * se resuelve igual que en http, leyendo el evento. Los destinatarios repiten los datos de su
 * envío, como en la respuesta del servicio.
 */
type SeedRecipient = Pick<
  NotificationHistoryItem,
  'id' | 'email' | 'name' | 'deliveryStatus' | 'recipientAction' | 'attemptCount' | 'lastError'
> & { sentAt: string | null; smtpQueuedAs?: string }

function seedBatch(
  batch: Omit<NotificationBatch, 'recipients' | 'fromAddress' | 'fromName'>,
  recipients: SeedRecipient[],
): NotificationBatch {
  const envio = {
    ...batch,
    fromAddress: 'notificaciones@empresa.example.com',
    fromName: 'Sorteo360',
  }
  return {
    ...envio,
    recipients: recipients.map(({ smtpQueuedAs, ...r }) => ({
      ...r,
      batchId: envio.id,
      type: envio.type,
      subject: envio.subject,
      language: envio.language,
      fromAddress: envio.fromAddress,
      fromName: envio.fromName,
      deliveryTrackingAvailable: envio.deliveryTrackingAvailable,
      queuedAt: envio.createdAt,
      sgMessageId: smtpQueuedAs ? `sg-${smtpQueuedAs}` : null,
      smtpQueuedAs: smtpQueuedAs ?? null,
      about: envio.about,
    })),
  }
}

